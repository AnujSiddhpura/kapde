export function tStaff(lang, key, vars) {
  const table = staffCopy[lang] || staffCopy.en
  let s = table[key] || staffCopy.en[key] || key
  if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.replaceAll(`{${k}}`, v) })
  return s
}

export function floorLabel(lang, floor) {
  const map = { 1: 'first', 2: 'second', 3: 'third', 4: 'fourth', 5: 'fifth', 6: 'sixth', 7: 'seventh', 8: 'eighth' }
  return tStaff(lang, map[floor] || 'floor')
}
